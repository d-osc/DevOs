#!/bin/sh
# Keep DevOsPM's dev CLI (pm-cli, DevLang) in the project runtime, separate from DevLang's own dev alias: a launcher in build/wsl/bin that runs
# pm-cli/main.dev with the DevLang runtime `d`.
set -eu
project_root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
source_root=${DEV_OS_PM_SOURCE:-"$project_root/pm-cli"}
prefix="$project_root/build/wsl/bin"
if [ ! -f "$source_root/main.dev" ]; then
    printf '%s\n' 'pm-cli is missing. Set DEV_OS_PM_SOURCE to its checkout.' >&2
    exit 1
fi
runtime=$(command -v d || true)
if [ -z "$runtime" ]; then printf '%s\n' 'The DevLang runtime (d) is required to run the dev package manager.' >&2; exit 1; fi
mkdir -p "$prefix"
launcher="$prefix/dev"
cat > "$launcher.tmp" <<EOF
#!/bin/sh
# Generated by tools/setup/bootstrap-pm.sh: the DevOsPM CLI is DevLang (pm-cli/main.dev), run by the runtime found at that time so a PATH without it still works.
DEV_LAUNCHER="$launcher" exec "$runtime" "$source_root/main.dev" -- "\$@"
EOF
chmod 755 "$launcher.tmp"
mv -f "$launcher.tmp" "$launcher"
if ! "$launcher" --version | grep -Eq '^dev [0-9]+\.[0-9]+\.[0-9]+'; then printf '%s\n' 'The launcher is not the dev package manager.' >&2; exit 1; fi
printf 'Package manager ready: %s\n' "$launcher"
