import {Gtk, GLib, Gio} from '@dev-os/core';
import {Windows} from '@dev-os/services/windows';
Gtk.init(null);
const directory = GLib.getenv('DEV_OS_TASK_VIEW_TEST');
if (!directory) throw new Error('Use task-view-smoke.dev');
const first = new Gtk.Window({title: 'Task View native one', default_width: 500, default_height: 300});
const second = new Gtk.Window({title: 'Task View native two', default_width: 500, default_height: 300});
first.add(new Gtk.Label({label: 'Task View test window one'})); second.add(new Gtk.Label({label: 'Task View test window two'}));
let closed = false;
first.connect('delete-event', () => {closed = true; first.hide(); return true;});
const tracker = new Windows();
const wait = () => new Promise<void>(resolve => GLib.timeout_add(GLib.PRIORITY_DEFAULT, 50, () => {resolve(); return GLib.SOURCE_REMOVE;}));
async function until(check: () => boolean, reason: string) {for (let i = 0; i < 150; i++) {if (check()) return; await wait();} throw new Error(reason);}
async function verify() {
    first.show_all(); second.show_all();
    await until(() => tracker.state.filter(window => window.title.startsWith('Task View native')).length === 2, 'Tracker did not discover fixture windows');
    await until(() => tracker.desktops.length === 4 && tracker.state.every(window => window.desktop !== undefined), 'Native desktop metadata unavailable');
    const secondId = tracker.state.find(window => window.title === 'Task View native two')!.id;
    await until(() => tracker.canCreateDesktop, 'Desktop creation capability unavailable');
    tracker.createDesktop();
    await until(() => tracker.desktops.length === 5 && tracker.desktops.some(desktop => desktop.id === 5 && desktop.active), 'New desktop was not created and activated');
    tracker.moveToDesktop(secondId, 5);
    await until(() => tracker.state.find(window => window.id === secondId)?.desktop === 5, 'Window did not move to new desktop');
    tracker.switchDesktop(1);
    await until(() => tracker.desktops.some(desktop => desktop.id === 1 && desktop.active), 'Cannot return from new desktop');
    tracker.moveToDesktop(secondId, 2);
    await until(() => tracker.state.find(window => window.id === secondId)?.desktop === 2, 'Window did not move to Desktop 2');
    tracker.switchDesktop(1);
    first.iconify(); second.iconify();
    await until(() => tracker.state.filter(window => window.minimized && window.title.startsWith('Task View native')).length === 2, 'Fixture windows did not minimize');
    GLib.file_set_contents(`${directory}/fixture-ready`, 'ready');
    await until(() => tracker.desktops.some(desktop => desktop.id === 2 && desktop.active), 'Task View did not switch to Desktop 2');
    GLib.file_set_contents(`${directory}/desktop-switched`, 'switched');
    await until(() => Gio.File.new_for_path(`${directory}/selected`).query_exists(null), 'Keyboard selection did not arrive');
    await until(() => tracker.state.some(window => window.id === secondId && window.active && !window.minimized), 'Task View did not activate and restore the Desktop 2 window');
    await until(() => tracker.canRemoveDesktop, 'Desktop removal capability unavailable');
    tracker.removeDesktop(2);
    await until(() => tracker.desktops.length === 4 && tracker.desktops.some(desktop => desktop.id === 1 && desktop.active) && tracker.state.find(window => window.id === secondId)?.desktop === 1, 'Removing active desktop did not preserve windows on the preceding desktop');
    tracker.removeDesktop(1);
    await until(() => tracker.desktops.length === 3 && tracker.desktops.some(desktop => desktop.id === 1 && desktop.active) && tracker.state.filter(window => window.title.startsWith('Task View native')).every(window => window.desktop === 1), 'Removing first desktop did not move windows to the next desktop');
    tracker.removeDesktop(3);
    await until(() => tracker.desktops.length === 2, 'Removing inactive desktop failed');
    tracker.removeDesktop(2);
    await until(() => tracker.desktops.length === 1, 'Removing down to one desktop failed');
    tracker.removeDesktop(1); tracker.removeDesktop(999);
    await wait(); await wait();
    if (tracker.desktops.length !== 1 || tracker.state.filter(window => window.title.startsWith('Task View native')).length !== 2) throw new Error('Final desktop protection failed or a window was lost');
    tracker.createDesktop();
    await until(() => tracker.desktops.length === 2 && tracker.desktops.some(desktop => desktop.id === 2 && desktop.active), 'Cannot create after removing desktops');
    const id = tracker.state.find(window => window.title === 'Task View native one')!.id;
    tracker.close(id); await until(() => closed, 'Native polite close request did not arrive');
    GLib.file_set_contents(`${directory}/fixture-passed`, 'passed');
}
const loop = new GLib.MainLoop(null, false); let failed: unknown;
void verify().catch(error => {failed = error; GLib.file_set_contents(`${directory}/fixture-failed`, String(error));}).finally(() => loop.quit());
loop.run(); tracker.destroy(); first.destroy(); second.destroy(); if (failed) throw failed;
